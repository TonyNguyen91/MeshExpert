# Light theme, generated from the dark one at build time (build.py calls light_css).
# Every rule of theme.css / app.css / dws.css that sets a colour gets a copy under html.light with the colour turned
# over: the hue stays, the lightness is flipped (dark panels become light, light text becomes dark), strong accent
# colours (orange, blue, green, red) stay as they are on backgrounds and get a little darker as text. Shadows keep
# their colour and get lighter. The Pico tokens and the colours drawn inside SVG icons are set by hand below.
import re, colorsys

HEX = re.compile(r'#([0-9a-fA-F]{3,8})\b')
RGB = re.compile(r'rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+%?)\s*)?\)')
PROPS = ('color', 'background', 'background-color', 'border', 'border-color', 'border-top', 'border-bottom', 'border-left',
         'border-right', 'border-top-color', 'border-bottom-color', 'border-left-color', 'border-right-color', 'outline',
         'outline-color', 'box-shadow', 'text-shadow', 'fill', 'stroke', 'scrollbar-color', 'caret-color', 'background-image')


def _flip(r, g, b, a, role):
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    accent = s > 0.45 and 0.3 < l < 0.8
    if role == 'shadow':
        if l < 0.3:
            return r, g, b, a * 0.35
        return r, g, b, a
    if accent:
        if role == 'text':
            l = l * 0.72
        else:
            return r, g, b, a
    else:
        l = 1 - l
        if role == 'text':
            l = min(l, 0.42)
        elif role == 'bg' and a < 0.99 and l > 0.8:
            pass
    r2, g2, b2 = colorsys.hls_to_rgb(h, max(0, min(1, l)), s)
    return round(r2 * 255), round(g2 * 255), round(b2 * 255), a


def _fmt(r, g, b, a):
    if a >= 0.999:
        return '#%02x%02x%02x' % (r, g, b)
    return 'rgba(%d,%d,%d,%s)' % (r, g, b, ('%.3f' % a).rstrip('0').rstrip('.'))


def flip_value(v, role):
    def hx(m):
        t = m.group(1)
        if len(t) in (3, 4):
            t = ''.join(c * 2 for c in t)
        r, g, b = int(t[0:2], 16), int(t[2:4], 16), int(t[4:6], 16)
        a = int(t[6:8], 16) / 255 if len(t) == 8 else 1
        return _fmt(*_flip(r, g, b, a, role))

    def rg(m):
        a = m.group(4)
        a = 1 if a is None else (float(a[:-1]) / 100 if a.endswith('%') else float(a))
        return _fmt(*_flip(float(m.group(1)), float(m.group(2)), float(m.group(3)), a, role))
    return RGB.sub(rg, HEX.sub(hx, v))


def _rules(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            return
        k = css.find('}', j)
        sel, body = css[i:j].strip(), css[j + 1:k]
        i = k + 1
        if sel.startswith('@') or not sel:
            continue
        yield sel, body


def _scope(sel):
    out = []
    for s in sel.split(','):
        s = s.strip()
        if not s:
            continue
        if s.startswith(':root'):
            out.append('html.light' + s[5:])
        elif s.startswith('html'):
            out.append('html.light' + s[4:])
        else:
            out.append('html.light ' + s)
    return ', '.join(out)


def light_css(css):
    out = []
    for sel, body in _rules(css):
        if sel.strip() == ':root':
            continue
        decl = []
        for d in body.split(';'):
            if ':' not in d:
                continue
            p, v = d.split(':', 1)
            p = p.strip().lower()
            v = v.strip()
            if p.startswith('--'):
                if HEX.search(v) or RGB.search(v):
                    decl.append('%s: %s' % (p, flip_value(v, 'bg')))
                continue
            if p not in PROPS or not (HEX.search(v) or RGB.search(v)):
                continue
            role = 'text' if p in ('color', 'caret-color', 'fill', 'stroke') else 'shadow' if p.endswith('shadow') else 'bg'
            decl.append('%s: %s' % (p, flip_value(v, role)))
        if decl:
            out.append('%s { %s; }' % (_scope(sel), '; '.join(decl)))
    return BASE + '\n'.join(out) + '\n' + ICONS


